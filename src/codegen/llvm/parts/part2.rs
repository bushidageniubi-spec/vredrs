    fn emit_string_globals(&mut self) {
        if self.strs.is_empty() {
            return;
        }
        self.buf.push_str("; --- String literals ---\n");
        let mut entries: Vec<(&String, &String)> = self.strs.iter().collect();
        entries.sort_by_key(|(_, n)| *n);
        for (text, name) in entries {
            let bytes = text.as_bytes();
            let len = bytes.len() + 1;
            let mut esc = String::new();
            for &b in bytes {
                match b {
                    b'\n' => esc.push_str("\\0A"),
                    b'\r' => esc.push_str("\\0D"),
                    b'\t' => esc.push_str("\\09"),
                    b'\\' => esc.push_str("\\5C"),
                    b'"' => esc.push_str("\\22"),
                    0x20..=0x7e => esc.push(b as char),
                    b => esc.push_str(&format!("\\{:02X}", b)),
                }
            }
            esc.push_str("\\00");
            self.buf.push_str(&format!(
                "{} = private unnamed_addr constant [{} x i8] c\"{}\", align 1\n",
                name, len, esc
            ));
        }
        self.buf.push('\n');
    }

    fn emit_class_vtables(&mut self, local_classes: &std::collections::HashSet<String>) {
        if self.classes.is_empty() {
            return;
        }
        self.buf.push_str("; --- Class vtables ---\n");
        let mut names: Vec<String> = self.classes.keys().cloned().collect();
        names.sort();
        for name in &names {
            // Only emit vtables for classes defined in THIS module. Classes
            // from imported modules are referenced as external symbols.
            if !local_classes.contains(name) {
                continue;
            }
            let c = self.classes[name].clone();
            let methods = c.methods.clone();
            let n = methods.len();
            let arr_name = format!("@{}.vmethods", self.safe(name));
            let vt_name = format!("@{}.vtable", self.safe(name));
            let parent_name = match &c.parent {
                Some(p) => format!("@{}.vtable", self.safe(p)),
                None => "null".to_string(),
            };
            let class_name_str = self.intern(name);
            let entries: Vec<String> = methods
                .iter()
                .map(|m| format!("i8* bitcast (ptr @{} to i8*)", m.llvm_name))
                .collect();
            let class_name_len = name.len() + 1;
            if n == 0 {
                self.buf.push_str(&format!(
                    "{} = private global [1 x i8*] [i8* null]\n",
                    arr_name
                ));
                self.buf.push_str(&format!(
                    "{} = global %vredrs.vtable {{ i64 0, ptr getelementptr inbounds ([1 x i8*], ptr {}, i64 0, i64 0), ptr {}, ptr getelementptr inbounds ([{} x i8], ptr {}, i64 0, i64 0) }}\n",
                    vt_name, arr_name, parent_name, class_name_len, class_name_str));
            } else {
                self.buf.push_str(&format!(
                    "{} = private global [{} x i8*] [{}]\n",
                    arr_name,
                    n,
                    entries.join(", ")
                ));
                self.buf.push_str(&format!(
                    "{} = global %vredrs.vtable {{ i64 {}, ptr getelementptr inbounds ([{} x i8*], ptr {}, i64 0, i64 0), ptr {}, ptr getelementptr inbounds ([{} x i8], ptr {}, i64 0, i64 0) }}\n",
                    vt_name, n, n, arr_name, parent_name, class_name_len, class_name_str));
            }
        }
        self.buf.push('\n');
    }

    /* -- function & method bodies -- */
    fn gen_function(&mut self, f: &FnDef) -> Result<()> {
        // If this function contains yield, compile it as a generator coroutine.
        if self.body_has_yield(&f.body) && !f.is_async {
            return self.gen_generator_function(f);
        }
        let sig = self.functions.get(&f.name.name).cloned().ok_or_else(|| {
            CompilerError::codegen_error(format!("missing sig for fn '{}'", f.name.name))
        })?;
        let mut params = String::new();
        for (i, p) in f.params.iter().enumerate() {
            if i > 0 {
                params.push_str(", ");
            }
            params.push_str(&format!("{} %{}", sig.params[i].ir(), p.name.name));
        }
        self.buf.push_str(&format!(
            "define {} @{}({}) {{\nentry:\n",
            sig.ret.ir(),
            self.safe(&f.name.name),
            params
        ));
        let mut vars: HashMap<String, LocalSlot> = HashMap::new();
        for (i, p) in f.params.iter().enumerate() {
            let ty = sig.params[i].clone();
            let ptr = self.new_local(&p.name.name);
            self.buf
                .push_str(&format!("  {} = alloca {}, align 8\n", ptr, ty.ir()));
            self.buf.push_str(&format!(
                "  store {} %{}, {}* {}, align 8\n",
                ty.ir(),
                p.name.name,
                ty.ir(),
                ptr
            ));
            vars.insert(
                p.name.name.clone(),
                LocalSlot {
                    ty: ty.clone(),
                    ptr,
                    class: self.class_of_annot(p.type_annotation.as_ref()),
                    async_fn: None,
                    closure_sig: None,
                },
            );
        }
        let terminated = self.gen_block(&f.body, &mut vars, &sig.ret)?;
        if !terminated {
            self.emit_default_ret(&sig.ret)?;
        }
        self.buf.push_str("}\n\n");
        Ok(())
    }

    /// Compile a generator function (one that contains `yield`).
    ///
    /// Eager semantics: the first poll runs the entire body, collecting all
    /// yielded values into a list stored in the coro's impl field. The first
    /// yielded value is returned. Subsequent polls read the next value from
    /// the list. When the list is exhausted, the coro is marked done.
    ///
    /// This means the generator body runs to completion on the first resume()
    /// call, and side effects in the body happen eagerly.
    fn gen_generator_function(&mut self, f: &FnDef) -> Result<()> {
        let ctor = self.safe(&f.name.name);
        let poll = format!("{}_poll", ctor);
        // Constructor: allocate coro + an empty list, return coro.
        self.buf
            .push_str(&format!("; generator {} constructor\n", f.name.name));
        self.buf
            .push_str(&format!("define %vredrs.coro* @{}() {{\nentry:\n", ctor));
        self.buf
            .push_str("  %coro = call %vredrs.coro* @vredrs_coro_alloc()\n");
        self.buf
            .push_str("  %list = call %vredrs.list* @vredrs_list_new()\n");
        self.buf.push_str(
            "  call void @vredrs_coro_set_list(%vredrs.coro* %coro, %vredrs.list* %list)\n",
        );
        self.buf
            .push_str("  call void @vredrs_coro_set_index(%vredrs.coro* %coro, i64 0)\n");
        self.buf.push_str("  ret %vredrs.coro* %coro\n}\n\n");
        // Poll function: on first call (state==0), run the body to collect
        // yields into the list. Then read the next value from the list.
        self.buf
            .push_str(&format!("; generator {} poll (eager)\n", f.name.name));
        self.buf.push_str(&format!(
            "define i1 @{}(%vredrs.coro* %coro) {{\nentry:\n",
            poll
        ));
        // Check if body has been run (state == 0 means not run yet).
        self.buf.push_str(
            "  %state.slot = getelementptr inbounds %vredrs.coro, ptr %coro, i32 0, i32 0\n",
        );
        self.buf
            .push_str("  %state = load i64, i64* %state.slot, align 8\n");
        self.buf.push_str("  %not_run = icmp eq i64 %state, 0\n");
        let run_body_lbl = self.new_lbl();
        let read_list_lbl = self.new_lbl();
        self.buf.push_str(&format!(
            "  br i1 %not_run, label %L{}, label %L{}\n",
            run_body_lbl, read_list_lbl
        ));
        // Run body: yield pushes to the list.
        self.buf.push_str(&format!("L{}:\n", run_body_lbl));
        let mut vars: HashMap<String, LocalSlot> = HashMap::new();
        vars.insert(
            "__coro".to_string(),
            LocalSlot {
                ty: Ty::Coro,
                ptr: "%coro.addr.synthetic".to_string(),
                class: None,
                async_fn: Some(f.name.name.clone()),
                    closure_sig: None,
            },
        );
        // Mark state as 1 (running) so yield knows to push to the list.
        self.buf
            .push_str("  call void @vredrs_coro_set_state(%vredrs.coro* %coro, i64 1)\n");
        let _ = self.gen_async_block(&f.body, &mut vars)?;
        // Body done. Set state to 2 (done collecting).
        self.buf
            .push_str("  call void @vredrs_coro_set_state(%vredrs.coro* %coro, i64 2)\n");
        self.buf
            .push_str(&format!("  br label %L{}\n", read_list_lbl));
        // Read next value from the list.
        self.buf.push_str(&format!("L{}:\n", read_list_lbl));
        self.buf
            .push_str("  %list = call %vredrs.list* @vredrs_coro_get_list(%vredrs.coro* %coro)\n");
        self.buf
            .push_str("  %idx = call i64 @vredrs_coro_get_index(%vredrs.coro* %coro)\n");
        self.buf
            .push_str("  %len = call i64 @vredrs_list_len(%vredrs.list* %list)\n");
        self.buf.push_str("  %has_more = icmp slt i64 %idx, %len\n");
        let has_more_lbl = self.new_lbl();
        let done_lbl = self.new_lbl();
        self.buf.push_str(&format!(
            "  br i1 %has_more, label %L{}, label %L{}\n",
            has_more_lbl, done_lbl
        ));
        self.buf.push_str(&format!("L{}:\n", has_more_lbl));
        self.buf.push_str(
            "  %val = call %vredrs.value @vredrs_list_get(%vredrs.list* %list, i64 %idx)\n",
        );
        self.buf.push_str("  %next_idx = add i64 %idx, 1\n");
        self.buf
            .push_str("  call void @vredrs_coro_set_index(%vredrs.coro* %coro, i64 %next_idx)\n");
        // Store the value as the coro result (as i64 for compatibility).
        self.buf
            .push_str("  %val_i64 = call i64 @vredrs_value_get_i64(%vredrs.value %val)\n");
        self.buf
            .push_str("  call void @vredrs_coro_store_result(%vredrs.coro* %coro, i64 %val_i64)\n");
        self.buf.push_str("  ret i1 false\n");
        self.buf.push_str(&format!("L{}:\n", done_lbl));
        self.buf
            .push_str("  call void @vredrs_coro_set_state(%vredrs.coro* %coro, i64 3)\n");
        self.buf.push_str("  ret i1 true\n");
        self.buf.push_str("}\n\n");
        Ok(())
    }

    fn gen_method_function(&mut self, c: &ClassInfo, m: &MethodInfo) -> Result<()> {
        let mut params = vec!["%vredrs.object* %self".to_string()];
        for (i, p) in m.fn_def.params.iter().enumerate() {
            params.push(format!("{} %{}", m.sig.params[i].ir(), p.name.name));
        }
        self.buf
            .push_str(&format!("; method {}.{}\n", c.name, m.name));
        self.buf.push_str(&format!(
            "define {} @{}({}) {{\nentry:\n",
            m.sig.ret.ir(),
            m.llvm_name,
            params.join(", ")
        ));
        let mut vars: HashMap<String, LocalSlot> = HashMap::new();
        let self_ptr = self.new_local("self");
        self.buf.push_str(&format!(
            "  {} = alloca %vredrs.object*, align 8\n",
            self_ptr
        ));
        self.buf.push_str(&format!(
            "  store %vredrs.object* %self, %vredrs.object** {}, align 8\n",
            self_ptr
        ));
        let self_ptr_clone = self_ptr.clone();
        vars.insert(
            "self".to_string(),
            LocalSlot {
                ty: Ty::Obj,
                ptr: self_ptr_clone,
                class: Some(c.name.clone()),
                async_fn: None,
                    closure_sig: None,
            },
        );
        if let Some(pn) = &c.parent {
            // super.method() — the IR uses the same self pointer but resolves
            // methods through the parent vtable. We store the parent class
            // name in a synthetic local so super-call codegen can find it.
            vars.insert(
                "__super_class".to_string(),
                LocalSlot {
                    ty: Ty::Obj,
                    ptr: self_ptr,
                    class: Some(pn.clone()),
                    async_fn: None,
                    closure_sig: None,
                },
            );
        }
        for (i, p) in m.fn_def.params.iter().enumerate() {
            let ty = m.sig.params[i].clone();
            let ptr = self.new_local(&p.name.name);
            self.buf
                .push_str(&format!("  {} = alloca {}, align 8\n", ptr, ty.ir()));
            self.buf.push_str(&format!(
                "  store {} %{}, {}* {}, align 8\n",
                ty.ir(),
                p.name.name,
                ty.ir(),
                ptr
            ));
            vars.insert(
                p.name.name.clone(),
                LocalSlot {
                    ty: ty.clone(),
                    ptr,
                    class: self.class_of_annot(p.type_annotation.as_ref()),
                    async_fn: None,
                    closure_sig: None,
                },
            );
        }
        let terminated = self.gen_block(&m.fn_def.body, &mut vars, &m.sig.ret)?;
        if !terminated {
            self.emit_default_ret(&m.sig.ret)?;
        }
        self.buf.push_str("}\n\n");
        Ok(())
    }


