    fn intern(&mut self, text: &str) -> String {
        if let Some(n) = self.strs.get(text) {
            return n.clone();
        }
        let name = format!("@.vstr.{}", self.str_n);
        self.str_n += 1;
        self.strs.insert(text.to_string(), name.clone());
        name
    }

    fn intern_str_for(&mut self, text: &str) -> Result<String> {
        let name = self.intern(text);
        let len = text.as_bytes().len() + 1;
        let cptr = self.new_var();
        self.buf.push_str(&format!(
            "  {} = getelementptr inbounds [{} x i8], ptr {}, i64 0, i64 0\n",
            cptr, len, name
        ));
        // Wrap the C string in a vredrs_str so dict/object helpers can read ->len / ->data.
        let sptr = self.new_var();
        self.buf.push_str(&format!(
            "  {} = call %vredrs.str* @vredrs_str_from_cstr(ptr {})\n",
            sptr, cptr
        ));
        Ok(sptr)
    }

